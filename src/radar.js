function generateRadarSVG(axes, title = "Security Radar") {
  const labels = Object.keys(axes);
  const values = Object.values(axes);
  const n = labels.length;
  const cx = 320, cy = 340, r = 180;
  const angleStep = (2 * Math.PI) / n;

  let points = "";
  let grid = "";
  let labelsSvg = "";
  let dots = "";

  for (let i = 0; i < n; i++) {
    const angle = -Math.PI / 2 + i * angleStep;
    const ratio = Math.max(0.08, values[i] / 100);
    const x = cx + Math.cos(angle) * r * ratio;
    const y = cy + Math.sin(angle) * r * ratio;
    points += `${x.toFixed(1)},${y.toFixed(1)} `;

    const gx = cx + Math.cos(angle) * r;
    const gy = cy + Math.sin(angle) * r;
    grid += `<line x1="${cx}" y1="${cy}" x2="${gx.toFixed(1)}" y2="${gy.toFixed(1)}" stroke="#2a2a2a" stroke-width="1"/>`;

    const lx = cx + Math.cos(angle) * (r + 36);
    const ly = cy + Math.sin(angle) * (r + 36);
    labelsSvg += `<text x="${lx.toFixed(1)}" y="${ly.toFixed(1)}" fill="#e6edf3" font-family="ui-monospace, SFMono-Regular, monospace" font-size="13" text-anchor="middle" dominant-baseline="middle">${labels[i]}</text>`;

    dots += `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="4" fill="#39d353"/>`;
  }

  let circles = "";
  for (let level = 25; level <= 100; level += 25) {
    const rr = r * (level / 100);
    circles += `<circle cx="${cx}" cy="${cy}" r="${rr}" fill="none" stroke="#21262d" stroke-width="1"/>`;
    circles += `<text x="${cx + 6}" y="${cy - rr + 12}" fill="#6e7681" font-family="monospace" font-size="10">${level}</text>`;
  }

  const avg = Math.round(values.reduce((a, b) => a + b, 0) / n);

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 680" width="640" height="680">
  <defs>
    <filter id="glow" x="-30%" y="-30%" width="160%" height="160%">
      <feGaussianBlur stdDeviation="6" result="blur"/>
      <feMerge>
        <feMergeNode in="blur"/>
        <feMergeNode in="SourceGraphic"/>
      </feMerge>
    </filter>
    <linearGradient id="fillGrad" x1="0%" y1="0%" x2="0%" y2="100%">
      <stop offset="0%" stop-color="#39d353" stop-opacity="0.45"/>
      <stop offset="100%" stop-color="#238636" stop-opacity="0.15"/>
    </linearGradient>
  </defs>
  <rect width="100%" height="100%" fill="#0d1117"/>
  <text x="320" y="42" fill="#f0f6fc" font-family="ui-monospace, monospace" font-size="22" text-anchor="middle" font-weight="700">${title}</text>
  <text x="320" y="68" fill="#8b949e" font-family="monospace" font-size="13" text-anchor="middle">Overall posture: ${avg}/100</text>
  ${circles}
  ${grid}
  <polygon points="${points.trim()}" fill="url(#fillGrad)" stroke="#39d353" stroke-width="2.5" filter="url(#glow)"/>
  ${dots}
  ${labelsSvg}
  <text x="320" y="640" fill="#6e7681" font-family="monospace" font-size="11" text-anchor="middle">Generated by secradar · higher = safer</text>
</svg>`;
}

module.exports = { generateRadarSVG };
